# The five shock tubes of Toro's Table 4.1, with the star states of his Table
# 4.3. Reproducing them is what makes this module usable as a reference. The
# values are kept as the book prints them, and the comparison only asks for the
# digits it actually printed: one unit of the last one, or six significant
# digits, whichever is looser. Test 5 needs the second bound, its initial data
# being the star state of tests 3 and 4 as the book rounded it before reusing
# it.
TORO_TESTS = {
    1: ((1.0, 0.0, 1.0), (0.125, 0.0, 0.1), "0.30313", "0.92745"),
    2: ((1.0, -2.0, 0.4), (1.0, 2.0, 0.4), "0.00189", "0.00000"),
    3: ((1.0, 0.0, 1000.0), (1.0, 0.0, 0.01), "460.894", "19.5975"),
    4: ((1.0, 0.0, 0.01), (1.0, 0.0, 100.0), "46.0950", "-6.19633"),
    5: ((5.99924, 19.5975, 460.894), (5.99242, -6.19633, 46.0950), "1691.64", "8.68975"),
}


def _printed_tolerance(text):
    """How far from a published value a value may sit and still match it."""
    decimals = len(text.split(".")[1]) if "." in text else 0
    return max(10.0**-decimals, 5e-6 * abs(float(text)))


def _self_test():
    print(f"{'test':>4}  {'p* (Toro)':>10} {'p* (here)':>14}  {'u* (Toro)':>10} {'u* (here)':>14}")
    ok = True
    for number, (left, right, p_ref, u_ref) in TORO_TESTS.items():
        p_star, u_star = star_state(left, right)
        print(f"{number:>4}  {p_ref:>10} {p_star:>14.6g}  {u_ref:>10} {u_star:>14.6g}")
        ok &= abs(p_star - float(p_ref)) <= _printed_tolerance(p_ref)
        ok &= abs(u_star - float(u_ref)) <= _printed_tolerance(u_ref)
    print("\nagrees with Table 4.3 to the printed digits" if ok else "\nDOES NOT agree with Table 4.3")
    return ok


if __name__ == "__main__":
    import sys

    sys.exit(0 if _self_test() else 1)
